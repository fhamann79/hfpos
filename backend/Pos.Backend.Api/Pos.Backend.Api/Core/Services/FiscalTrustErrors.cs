namespace Pos.Backend.Api.Core.Services;

public static class FiscalTrustErrors
{
    public static bool IsValidation(string code) => code is
        "FISCAL_TRUST_GUARD_REQUIRED" or "FISCAL_TRUST_CAPACITY" or "FISCAL_TRUST_EVALUATION_ERROR"
        or "FISCAL_TRUST_REGISTRY_UNAVAILABLE" or "FISCAL_TRUST_REGISTRY_UNREADABLE"
        or "FISCAL_TRUST_REGISTRY_NOT_APPROVED" or "FISCAL_TRUST_REGISTRY_INVALID" or "FISCAL_TRUST_REGISTRY_STALE"
        or "CERTIFICATE_CHAIN_BUILD_FAILED" or "CERTIFICATE_AUTHORITY_INVALID" or "CERTIFICATE_POLICY_NOT_SUPPORTED"
        or "CERTIFICATE_VALIDITY_INVALID" or "CERTIFICATE_SIGNING_PROFILE_UNSUPPORTED" or "CERTIFICATE_RUC_MISMATCH"
        or "CERTIFICATE_REVOCATION_REVOKED" or "CERTIFICATE_REVOCATION_SUSPENDED"
        or "CERTIFICATE_REVOCATION_UNKNOWN" or "CERTIFICATE_REVOCATION_STALE" or "CERTIFICATE_REVOCATION_ERROR"
        or "FISCAL_OCSP_NOT_IMPLEMENTED" or "FISCAL_CERTIFICATE_LIMIT" or "FISCAL_SIGNED_XML_INVALID"
        or "CERTIFICATE_SIGNER_AMBIGUOUS" or "CERTIFICATE_COLLECTION_LIMIT" or "CERTIFICATE_IMPORT_CAPACITY";
}
