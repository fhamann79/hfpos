namespace Pos.Backend.Api.Core.Services;

public static class FiscalProfileErrors
{
    public static bool IsValidation(string code) => code is
        "NON_INVENTORY_REQUIRES_CURRENT_SERVICE"
        or "FISCAL_PROFILE_REQUIRED" or "FISCAL_PROFILE_CONFIRMATION_REQUIRED" or "FISCAL_PROFILE_INCOMPATIBLE"
        or "RIMPE_ELIGIBILITY_CONFIRMATION_REQUIRED" or "FISCAL_PROFILE_NOT_EFFECTIVE"
        or "FISCAL_PROFILE_EFFECTIVE_DATE_INVALID" or "FISCAL_PROFILE_ALREADY_USED_CHANGE_NEXT_DATE"
        or "FISCAL_RESOLUTION_INVALID" or "PRODUCT_FISCAL_CLASSIFICATION_REQUIRED"
        or "PRODUCT_FISCAL_CLASSIFICATION_INVALID" or "FISCAL_ACTIVITY_UNDETERMINED"
        or "RIMPE_EXCLUDED_ACTIVITY_UNSUPPORTED" or "FISCAL_CLASSIFICATION_CONFLICT"
        or "FISCAL_LEGAL_BASIS_UNSUPPORTED" or "FISCAL_OPERATION_FACTS_UNSUPPORTED"
        or "SRI_MATERIAL_CODE_REQUIRED" or "FISCAL_DATE_RULE_UNSUPPORTED"
        or "FISCAL_PREVIEW_REQUIRED" or "FISCAL_PREVIEW_CHANGED" or "FISCAL_PROFILE_REVISION_CONFLICT"
        or "PRODUCT_FISCAL_REVISION_CONFLICT" or "CREDIT_NOTE_FISCAL_TRANSITION_UNSUPPORTED"
        or "CREDIT_NOTE_LEGACY_FISCAL_CONTEXT_REQUIRED" or "FISCAL_LEGACY_REVIEW_REQUIRED";
}
