namespace Pos.Backend.Api.Core.Services;

public static class FiscalCertificateErrors
{
    public static bool IsValidation(string code) => code is
        "FISCAL_CERTIFICATE_GUARD_REQUIRED" or "FISCAL_CERTIFICATE_PROVIDER_REQUIRED" or "FISCAL_SIGNED_XML_INVALID"
        or "CERTIFICATE_SIGNING_PROFILE_UNSUPPORTED" or "CERTIFICATE_RUC_MISMATCH"
        or "CERTIFICATE_PRIVATE_KEY_UNUSABLE" or "CERTIFICATE_PRIVATE_KEY_MISMATCH"
        or "CERTIFICATE_SIGNER_AMBIGUOUS" or "CERTIFICATE_COLLECTION_LIMIT" or "CERTIFICATE_IMPORT_CAPACITY"
        or "CERTIFICATE_NOT_YET_VALID" or "CERTIFICATE_EXPIRED" or "CERTIFICATE_WITHOUT_PRIVATE_KEY"
        or "CERTIFICATE_UNPROTECT_FAILED" or "CERTIFICATE_LOAD_FAILED";
}
